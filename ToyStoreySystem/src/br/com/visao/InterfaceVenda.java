    private void jBadicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBadicionarActionPerformed
        String codigo = jTcodigo.getText().trim();
        if (codigo.isEmpty()) {
            mostrarErro("Informe o código de barras.");
            jTcodigo.requestFocus();
            return;
        }

        int qtd;
        try {
            qtd = Integer.parseInt(jTquantidade.getText().trim());
        } catch (NumberFormatException ex) {
            mostrarErro("Quantidade inválida. Use um número inteiro.");
            jTquantidade.requestFocus();
            return;
        }
        if (qtd <= 0) {
            mostrarErro("A quantidade deve ser maior que zero.");
            jTquantidade.requestFocus();
            return;
        }

        try {
            Produto p = new CRUDProduto().encontrarPorCodigoBarras(codigo);
            if (p == null) {
                mostrarErro("Nenhum produto com o código " + codigo + ".");
                jTcodigo.requestFocus();
                return;
            }
            if (!"Ativo".equals(p.getStatus())) {
                mostrarErro("O produto \"" + p.getNome() + "\" está inativo.");
                return;
            }

            // Mesmo produto já no carrinho: soma a quantidade na linha existente
            for (int i = 0; i < modelo.getRowCount(); i++) {
                if ((int) modelo.getValueAt(i, 0) == p.getId()) {
                    int novaQtd = (int) modelo.getValueAt(i, 2) + qtd;
                    modelo.setValueAt(novaQtd, i, 2);
                    modelo.setValueAt(p.getPrecoVenda().multiply(BigDecimal.valueOf(novaQtd)), i, 4);
                    recalcularTotal();
                    mostrarSucesso("Quantidade de \"" + p.getNome() + "\" atualizada.");
                    jTcodigo.setText("");
                    jTquantidade.setText("1");
                    jTcodigo.requestFocus();
                    return;
                }
            }

            modelo.addRow(new Object[]{
                p.getId(), p.getNome(), qtd, p.getPrecoVenda(),
                p.getPrecoVenda().multiply(BigDecimal.valueOf(qtd))
            });
            recalcularTotal();
            mostrarSucesso("\"" + p.getNome() + "\" adicionado.");
            jTcodigo.setText("");
            jTquantidade.setText("1");
            jTcodigo.requestFocus();
        } catch (Exception ex) {
            mostrarErro("Não foi possível buscar o produto.");
            Logger.getLogger(InterfaceVenda.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jBadicionarActionPerformed

    private void jBremoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBremoverActionPerformed
        int linha = jTcarrinho.getSelectedRow();
        if (linha == -1) {
            mostrarErro("Selecione um item do carrinho para remover.");
            return;
        }
        modelo.removeRow(linha);
        recalcularTotal();
        mostrarSucesso("Item removido.");
    }//GEN-LAST:event_jBremoverActionPerformed

