    private void jBfinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBfinalizarActionPerformed
        int idFuncionario;
        try {
            idFuncionario = Integer.parseInt(jTfuncionario.getText().trim());
        } catch (NumberFormatException ex) {
            mostrarErro("Informe o id do funcionário (número).");
            jTfuncionario.requestFocus();
            return;
        }

        Integer idCliente = null;
        String txtCliente = jTcliente.getText().trim();
        if (!txtCliente.isEmpty()) {
            try {
                idCliente = Integer.valueOf(txtCliente);
            } catch (NumberFormatException ex) {
                mostrarErro("Id do cliente inválido. Deixe em branco para venda sem cliente.");
                jTcliente.requestFocus();
                return;
            }
        }

        if (modelo.getRowCount() == 0) {
            mostrarErro("O carrinho está vazio.");
            return;
        }

        List<CRUDVenda.ItemCarrinho> itens = new ArrayList<>();
        for (int i = 0; i < modelo.getRowCount(); i++) {
            itens.add(new CRUDVenda.ItemCarrinho(
                    (int) modelo.getValueAt(i, 0),
                    (int) modelo.getValueAt(i, 2)));
        }

        String forma = (String) jCforma.getSelectedItem();
        boolean simular = jCsimular.isSelected();

        try {
            int idVenda = new CRUDVenda().registrarVenda(idFuncionario, idCliente, itens, forma, simular);
            mostrarSucesso("Venda " + idVenda + " registrada com sucesso!");
            limparCarrinho();
        } catch (RegraNegocioException ex) {
            mostrarErro(ex.getMessage());
        } catch (java.sql.SQLException ex) {
            switch (ex.getErrorCode()) {
                case 3819:
                    mostrarErro("Estoque insuficiente para um dos itens.");
                    break;
                case 1213:
                    mostrarErro("Conflito com outra venda em andamento. Tente novamente.");
                    break;
                case 1205:
                    mostrarErro("O sistema está ocupado. Tente novamente em instantes.");
                    break;
                case 1452:
                    mostrarErro("Funcionário ou cliente inválido.");
                    break;
                default:
                    mostrarErro("Não foi possível registrar a venda.");
            }
            Logger.getLogger(InterfaceVenda.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IllegalStateException ex) {
            // Falha simulada: o ROLLBACK já aconteceu dentro do CRUDVenda
            mostrarErro("Falha simulada: a transação foi desfeita (ROLLBACK). Nada foi gravado.");
        } catch (Exception ex) {
            mostrarErro("Não foi possível registrar a venda.");
            Logger.getLogger(InterfaceVenda.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jBfinalizarActionPerformed

    private void jBconsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBconsultarActionPerformed
        int id;
        try {
            id = Integer.parseInt(jTconsultaid.getText().trim());
        } catch (NumberFormatException ex) {
            mostrarErro("Informe um ID numérico válido.");
            jTconsultaid.requestFocus();
            return;
        }

        try {
            Venda v = new CRUDVenda().encontrar(id);
            if (v == null) {
                mostrarErro("Venda não encontrada (id " + id + ").");
            } else {
                String cliente = (v.getIdCliente() == null) ? "sem cliente" : "cliente " + v.getIdCliente();
                mostrarSucesso("Venda " + v.getId() + " | "
                        + v.getDataHora().format(DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm"))
                        + " | " + moeda(v.getValorTotal()) + " | " + v.getStatus() + " | " + cliente);
            }
        } catch (Exception ex) {
            mostrarErro("Não foi possível consultar a venda.");
            Logger.getLogger(InterfaceVenda.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jBconsultarActionPerformed

    
    private void mostrarErro(String msg) {
    jLresultado.setForeground(java.awt.Color.RED);
    jLresultado.setText(msg);
}

private void mostrarSucesso(String msg) {
    jLresultado.setForeground(new java.awt.Color(0, 128, 0));
    jLresultado.setText(msg);
}

private String moeda(BigDecimal v) {
    return NumberFormat.getCurrencyInstance(Locale.forLanguageTag("pt-BR")).format(v);
}

private void recalcularTotal() {
    BigDecimal total = BigDecimal.ZERO;
    for (int i = 0; i < modelo.getRowCount(); i++) {
        total = total.add((BigDecimal) modelo.getValueAt(i, 4));
    }
    jLtotal.setText("Total: " + moeda(total));
}

private void limparCarrinho() {
    modelo.setRowCount(0);
    jTcodigo.setText("");
    jTquantidade.setText("1");
    recalcularTotal();
}
