    private void jBconsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBconsultarActionPerformed
        LocalDate ini = parseData(jTinicio.getText());
        if (ini == null) {
            mostrarErro("Data inicial inválida. Use dd/MM/aaaa (ex.: 01/10/2026).");
            jTinicio.requestFocus();
            return;
        }
        
        LocalDate fim = parseData(jTfim.getText());
        if (fim == null) {
            mostrarErro("Data final inválida. Use dd/MM/aaaa (ex.: 14/10/2026).");
            jTfim.requestFocus();
            return;
        }
        
        if (fim.isBefore(ini)) {
            mostrarErro("A data final não pode ser anterior à data inicial.");
            jTfim.requestFocus();
            return;
        }

        String forma = (String) jCforma.getSelectedItem();
        if ("Todas".equals(forma)) {
            forma = null;
        }

        try {
            List<Object[]> linhas = new CRUDConsulta().vendasPorFuncionario(
                    ini.atStartOfDay(), fim.plusDays(1).atStartOfDay(), forma);

            modelo.setRowCount(0);
            BigDecimal soma = BigDecimal.ZERO;
            for (Object[] l : linhas) {
                soma = soma.add((BigDecimal) l[3]);
                modelo.addRow(new Object[]{
                    l[0], l[1], l[2], moeda((BigDecimal) l[3]), moeda((BigDecimal) l[4])
                });
            }

            if (linhas.isEmpty()) {
                mostrarErro("Nenhuma venda encontrada no período.");
            } else {
                mostrarSucesso(linhas.size() + " linha(s) | Total geral: " + moeda(soma));
            }
        } catch (Exception ex) {
            mostrarErro("Não foi possível realizar a consulta.");
            Logger.getLogger(InterfaceConsultaVendas.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jBconsultarActionPerformed

    
    
    private void mostrarErro(String msg) {
        jLresultado.setForeground(java.awt.Color.RED);
        jLresultado.setText(msg);
    }

    private void mostrarSucesso(String msg) {
        jLresultado.setForeground(new java.awt.Color(0, 128, 0));
        jLresultado.setText(msg);
    }

    private String moeda(BigDecimal v) {
        return NumberFormat.getCurrencyInstance(Locale.forLanguageTag("pt-BR")).format(v);
    }

    /** Devolve null se o texto não for uma data válida. */
    private LocalDate parseData(String texto) {
        try {
            return LocalDate.parse(texto.trim(), FORMATO_DATA);
        } catch (DateTimeParseException ex) {
            return null;
        }
    }
