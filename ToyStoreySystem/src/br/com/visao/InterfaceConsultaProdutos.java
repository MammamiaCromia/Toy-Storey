    private void carregarCategorias() {
        try {
            List<CategoriaItem> cats = new CRUDProduto().listarCategorias();
            CategoriaItem[] itens = new CategoriaItem[cats.size() + 1];
            itens[0] = new CategoriaItem(0, "Todas as categorias");   // id 0 = sem filtro
            for (int i = 0; i < cats.size(); i++) {
                itens[i + 1] = cats.get(i);
            }
            jCcategoria.setModel(new DefaultComboBoxModel<>(itens));
        } catch (Exception ex) {
            mostrarErro("Não foi possível carregar as categorias.");
            Logger.getLogger(InterfaceConsultaProdutos.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

