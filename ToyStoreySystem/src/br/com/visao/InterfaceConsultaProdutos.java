    private void mostrarErro(String msg) {
        jLresultado.setForeground(java.awt.Color.RED);
        jLresultado.setText(msg);
    }

    private void mostrarSucesso(String msg) {
        jLresultado.setForeground(new java.awt.Color(0, 128, 0));
        jLresultado.setText(msg);
    }

    private String moeda(BigDecimal v) {
        return NumberFormat.getCurrencyInstance(Locale.forLanguageTag("pt-BR")).format(v);
    }

    /** Devolve null se o texto não for uma data válida. */
    private LocalDate parseData(String texto) {
        try {
            return LocalDate.parse(texto.trim(), FORMATO_DATA);
        } catch (DateTimeParseException ex) {
            return null;
        }
    }
