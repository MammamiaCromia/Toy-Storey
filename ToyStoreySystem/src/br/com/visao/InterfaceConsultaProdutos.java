    private void jBconsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBconsultarActionPerformed
        LocalDate ini = parseData(jTinicio.getText());
        if (ini == null) {
            mostrarErro("Data inicial inválida. Use dd/MM/aaaa (ex.: 01/10/2026).");
            jTinicio.requestFocus();
            return;
        }
        
        LocalDate fim = parseData(jTfim.getText());
        if (fim == null) {
            mostrarErro("Data final inválida. Use dd/MM/aaaa (ex.: 14/10/2026).");
            jTfim.requestFocus();
            return;
        }
        
        if (fim.isBefore(ini)) {
            mostrarErro("A data final não pode ser anterior à data inicial.");
            jTfim.requestFocus();
            return;
        }

        int minimo;
        try {
            minimo = Integer.parseInt(jTminimo.getText().trim());
        } catch (NumberFormatException ex) {
            mostrarErro("Quantidade mínima inválida. Use um número inteiro.");
            jTminimo.requestFocus();
            return;
        }
        
        if (minimo < 0) {
            mostrarErro("A quantidade mínima não pode ser negativa.");
            jTminimo.requestFocus();
            return;
        }

        CategoriaItem cat = (CategoriaItem) jCcategoria.getSelectedItem();
        Integer idCategoria = (cat == null || cat.getId() == 0) ? null : cat.getId();

        try {
            List<Object[]> linhas = new CRUDConsulta().produtosMaisVendidos(
                    ini.atStartOfDay(), fim.plusDays(1).atStartOfDay(), idCategoria, minimo);

            modelo.setRowCount(0);
            BigDecimal receita = BigDecimal.ZERO;
            for (Object[] l : linhas) {
                receita = receita.add((BigDecimal) l[3]);
                modelo.addRow(new Object[]{l[0], l[1], l[2], moeda((BigDecimal) l[3])});
            }

            if (linhas.isEmpty()) {
                mostrarErro("Nenhum produto atende aos filtros informados.");
            } else {
                mostrarSucesso(linhas.size() + " produto(s) | Receita: " + moeda(receita));
            }
        } catch (Exception ex) {
            mostrarErro("Não foi possível realizar a consulta.");
            Logger.getLogger(InterfaceConsultaProdutos.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jBconsultarActionPerformed

