    private void jBentrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBentrarActionPerformed
            String login = jTlogin.getText().trim();
    char[] senha = jPsenha.getPassword();

    if (login.isEmpty() || senha.length == 0) {
        mostrarErro("Informe o login e a senha.");
        return;
    }

    try {
        CRUDLogin.Usuario u = new CRUDLogin().autenticar(login, new String(senha));
        if (u == null) {
            mostrarErro("Login ou senha inválidos.");
            jPsenha.setText("");
            jPsenha.requestFocus();
            return;
        }
        Sessao.iniciar(u.getId(), u.getNome(), u.getCargo());
        new InterfaceInicio().setVisible(true);
        dispose();
    } catch (java.sql.SQLException ex) {
        mostrarErro("Não foi possível conectar ao banco de dados.");
        Logger.getLogger(InterfaceLogin.class.getName()).log(Level.SEVERE, null, ex);
    } catch (Exception ex) {
        mostrarErro("Não foi possível realizar o login.");
        Logger.getLogger(InterfaceLogin.class.getName()).log(Level.SEVERE, null, ex);
    } finally {
        java.util.Arrays.fill(senha, ' ');
    }
    }//GEN-LAST:event_jBentrarActionPerformed

