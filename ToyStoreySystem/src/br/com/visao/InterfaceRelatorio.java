    private void jBgerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBgerarActionPerformed
        LocalDate ini = parseData(jTinicio.getText());
        if (ini == null) {
            mostrarErro("Data inicial inválida. Use dd/MM/aaaa (ex.: 01/10/2026).");
            jTinicio.requestFocus();
            return;
        }
        
        LocalDate fim = parseData(jTfim.getText());
        if (fim == null) {
            mostrarErro("Data final inválida. Use dd/MM/aaaa (ex.: 14/10/2026).");
            jTfim.requestFocus();
            return;
        }
        
        if (fim.isBefore(ini)) {
            mostrarErro("A data final não pode ser anterior à data inicial.");
            jTfim.requestFocus();
            return;
        }

        try {
            List<Object[]> linhas = new CRUDConsulta().resumoDiario(ini, fim);

            modelo.setRowCount(0);
            DateTimeFormatter saida = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            int totalVendas = 0;
            int totalItens = 0;
            BigDecimal totalFaturamento = BigDecimal.ZERO;

            for (Object[] l : linhas) {
                totalVendas += (int) l[1];
                totalItens += (int) l[2];
                totalFaturamento = totalFaturamento.add((BigDecimal) l[3]);
                modelo.addRow(new Object[]{
                    ((LocalDate) l[0]).format(saida),
                    l[1],
                    l[2],
                    moeda((BigDecimal) l[3]),
                    moeda((BigDecimal) l[4])
                });
            }

            if (linhas.isEmpty()) {
                mostrarErro("Nenhuma venda concluída no período.");
            } else {
                mostrarSucesso(linhas.size() + " dia(s) | " + totalVendas + " venda(s) | "
                        + totalItens + " item(ns) | Faturamento: " + moeda(totalFaturamento));
            }
        } catch (Exception ex) {
            mostrarErro("Não foi possível gerar o relatório.");
            Logger.getLogger(InterfaceRelatorio.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jBgerarActionPerformed

    
    private void mostrarErro(String msg) {
        jLresultado.setForeground(java.awt.Color.RED);
        jLresultado.setText(msg);
    }

    private void mostrarSucesso(String msg) {
        jLresultado.setForeground(new java.awt.Color(0, 128, 0));
        jLresultado.setText(msg);
    }

    private String moeda(BigDecimal v) {
        return NumberFormat.getCurrencyInstance(Locale.forLanguageTag("pt-BR")).format(v);
    }

    /** Devolve null se o texto não for uma data válida. */
    private LocalDate parseData(String texto) {
        try {
            return LocalDate.parse(texto.trim(), FORMATO_DATA);
        } catch (DateTimeParseException ex) {
            return null;
        }
    }
